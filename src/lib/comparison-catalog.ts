export const MAX_COMPARISON_COUNTRIES = COMPARISON_CATALOG.length;

export function encodeCountrySet(slugs: readonly string[]): string {
  return "v1." + [...new Set(slugs)].map(slug => COMPARISON_CATALOG.indexOf(slug as typeof COMPARISON_CATALOG[number])).filter(index => index >= 0).map(index => index.toString(36).padStart(2, "0")).join("");
}

export function decodeCountrySet(value: unknown): string[] {
  if (typeof value !== "string" || !/^v1\.(?:[0-9a-z]{2}){1,195}$/.test(value)) return [];
  const indices = value.slice(3).match(/.{2}/g) ?? [];
  if (indices.some(index => parseInt(index, 36) >= COMPARISON_CATALOG.length)) return [];
  return [...new Set(indices.map(index => COMPARISON_CATALOG[parseInt(index, 36)]))];
}
