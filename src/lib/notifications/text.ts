export type NotificationTextKey = keyof typeof copy;
export function notificationText(
  locale: Locale,
  key: NotificationTextKey,
): string {
  return copy[key][Math.max(0, order.indexOf(locale))];
}
export function localizedNotification<T extends NotificationEvent>(
  item: T,
  locale: Locale,
): T {
  const type = item.key.startsWith("product:release:")
    ? "release"
    : item.key.startsWith("research:")
      ? "researchEvent"
      : item.key.startsWith("reminder:")
        ? "reminder"
        : item.key.startsWith("credential:")
          ? "credential"
          : item.key.startsWith("account:welcome")
            ? "welcome"
            : item.key.startsWith("next:") ||
                item.key.startsWith("onboarding:") ||
                item.key.startsWith("documents:")
              ? "next"
              : item.key.startsWith("course:")
                ? "learning"
                : item.key.startsWith("community:")
                  ? "community"
                  : item.key.startsWith("product:notification-center")
                    ? "product"
                    : item.category === "billing"
                      ? "billing"
                      : undefined;
  if (!type || locale === "en") return item;
  return {
    ...item,
    title: notificationText(
      locale,
      type === "billing" && /past_due|unpaid/.test(item.key)
        ? "paymentTitle"
        : `${type}Title`,
    ),
    body: notificationText(locale, `${type}Body`),
    actionLabel: notificationText(locale, "open"),
  };
}
